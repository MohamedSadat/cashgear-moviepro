//! Files the user chose, by opaque id. The `cgv-media://` protocol serves only
//! registered files, never arbitrary paths.
use serde::Serialize;
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::Mutex;

/// What the webview needs to read a registered file.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RegisteredMedia {
    pub id: String,
    pub path: String,
    pub name: String,
    pub size: u64,
    pub url: String,
}

/// The URL a webview uses for a registered id. WebView2 serves custom schemes
/// as `http://<scheme>.localhost`; WKWebView and WebKitGTK use the scheme itself.
pub fn media_url(id: &str) -> String {
    if cfg!(windows) {
        format!("http://cgv-media.localhost/{id}")
    } else {
        format!("cgv-media://localhost/{id}")
    }
}

/// Ids are generated by the UI (UUIDs) or derived from them; keep them URL- and file-safe.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 128
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.')
        && !id.starts_with('.')
}

#[derive(Default)]
pub struct Registry {
    files: Mutex<HashMap<String, PathBuf>>,
}

impl Registry {
    /// Registers an existing regular file under `id`, replacing any earlier entry.
    pub fn register(&self, id: &str, path: &Path) -> Result<RegisteredMedia, String> {
        if !valid_id(id) {
            return Err(format!("Invalid media id {id:?}"));
        }
        let metadata = std::fs::metadata(path)
            .map_err(|error| format!("{} cannot be read: {error}", path.display()))?;
        if !metadata.is_file() {
            return Err(format!("{} is not a file", path.display()));
        }
        let canonical = path
            .canonicalize()
            .map_err(|error| format!("{}: {error}", path.display()))?;
        self.files
            .lock()
            .expect("registry lock")
            .insert(id.to_string(), canonical);
        Ok(RegisteredMedia {
            id: id.to_string(),
            path: path.display().to_string(),
            name: path
                .file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default(),
            size: metadata.len(),
            url: media_url(id),
        })
    }

    pub fn path(&self, id: &str) -> Option<PathBuf> {
        self.files.lock().expect("registry lock").get(id).cloned()
    }

    pub fn forget(&self, id: &str) {
        self.files.lock().expect("registry lock").remove(id);
    }

    /// The id from a protocol request path such as `/1f0c…`.
    pub fn id_from_uri_path(path: &str) -> Option<&str> {
        let id = path.trim_start_matches('/');
        valid_id(id).then_some(id)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registers_files_and_serves_them_by_id() {
        let file = std::env::temp_dir().join("cgv-registry-test.bin");
        std::fs::write(&file, b"12345").unwrap();
        let registry = Registry::default();
        let media = registry.register("abc-1", &file).unwrap();
        assert_eq!(media.size, 5);
        assert_eq!(media.name, "cgv-registry-test.bin");
        assert!(media.url.ends_with("/abc-1"));
        assert_eq!(registry.path("abc-1"), Some(file.canonicalize().unwrap()));
        registry.forget("abc-1");
        assert_eq!(registry.path("abc-1"), None);
        std::fs::remove_file(file).unwrap();
    }

    #[test]
    fn refuses_bad_ids_and_missing_files() {
        let registry = Registry::default();
        assert!(registry.register("../x", Path::new("Cargo.toml")).is_err());
        assert!(registry
            .register("ok", Path::new("definitely-missing.mov"))
            .is_err());
        assert!(registry.register("dir", Path::new(".")).is_err());
        assert_eq!(Registry::id_from_uri_path("/abc-1"), Some("abc-1"));
        assert_eq!(Registry::id_from_uri_path("/a/b"), None);
        assert_eq!(Registry::id_from_uri_path("/..secret"), None);
        assert!(valid_id("2c1d0f7e-aaaa-4bbb-8ccc-0123456789ab.proxy"));
    }
}
